import assert from 'node:assert/strict';
import { build } from 'esbuild';
const result = await build({ entryPoints: ['src/editors/circuit-wires.ts'], bundle: true, write: false, format: 'esm' });
const { connectedWires, projectOnWire, wireJunctions } = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
const w = (id, a, b) => ({ id, part: 'short', a, b });
const chain = [w('a', [0, 0], [2, 0]), w('b', [2, 0], [2, 2]), w('c', [2, 2], [4, 2]), w('separate', [5, 5], [6, 5])];
assert.deepEqual([...connectedWires(chain, new Set(['a']))].sort(), ['a', 'b', 'c']);
assert.deepEqual([...connectedWires(chain, new Set(['c']))].sort(), ['a', 'b', 'c']);
const branch = w('branch', [1, 0], [1, -2]);
assert.equal(connectedWires([...chain, branch], new Set(['branch'])).size, 4);
assert.deepEqual(wireJunctions([...chain, branch]).map(j => j.p), [[1, 0]]);
assert.equal(connectedWires([w('h', [-1, 0], [1, 0]), w('v', [0, -1], [0, 1])], new Set(['h'])).size, 1, 'crossing alone is not a junction');
assert.equal(connectedWires([w('h', [-1, 0], [1, 0]), w('v', [0, -1], [0, 1]), { id: 'dot', part: 'circ', p: [0, 0] }], new Set(['h'])).size, 3, 'explicit dot joins crossing');
assert.deepEqual(projectOnWire([1, .1], chain[0]), [1, 0]);
assert.deepEqual(projectOnWire([-1, .1], chain[0]), [0, 0]);
console.log('Circuit wire connectivity checks passed');
const crossing = { id: 'jump', part: 'wires:jump-crossing', p: [0, 0] };
const split = [w('l', [-2, 0], [-.14, 0]), w('r', [.14, 0], [2, 0]), w('d', [0, -2], [0, -.14]), w('u', [0, .14], [0, 2]), crossing];
assert.deepEqual([...connectedWires(split, new Set(['l']))].sort(), ['l', 'r'], 'jump keeps horizontal run connected after code roundtrip');
assert.deepEqual([...connectedWires(split, new Set(['d']))].sort(), ['d', 'u'], 'jump isolates vertical run');
