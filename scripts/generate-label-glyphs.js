// Extract the bundled fonts' exact outlines once, at build maintenance time.
// The browser ships these tables, not a WOFF2 decoder or a general font engine.
const fs = require('fs');
const path = require('path');
const fontkit = require('fontkit');
const root = path.resolve(__dirname, '..');
// KaTeX's faces, then TeX's script-size faces (copies of KaTeX's with the 7pt and 5pt glyphs: scripts/generate-script-fonts.py)
const css = ['katex.min.css', 'katex-scripts.css'].map(file => fs.readFileSync(path.join(root, 'public/vendor/katex', file), 'utf8')).join('\n');
const fonts = {}, copyrights = new Set();
// a face that is another face's file (aliases), or a copy of one with some glyphs replaced (derived: only those kept)
const byFile = {}, aliases = {}, derived = {};
// a glyph the copy kept: its outline is KaTeX's, raised from quadratic to cubic curves, so the same advance and bounds
const same = (a, b) => a && a[0] === b[0] && [2, 3, 4, 5].every(i => Math.abs(a[i] - b[i]) < 0.01);
// Curve-extrema calculations differ in their last floating-point bits between
// V8 versions. Canonicalize calculated bounds, not the SVG outlines, to a
// nanounit in font coordinates so checked-in tables are runtime-independent.
const bound = value => Number(value.toFixed(9));
for (const match of css.matchAll(/@font-face\s*\{[^}]*\}/g)) {
  const rule = match[0];
  const property = name => new RegExp(name + '\\s*:\\s*([^;}]*)').exec(rule)?.[1].trim().replace(/["']/g, '');
  const file = /url\(['"]?([^'")]+\.woff2)['"]?\)/.exec(rule)[1].split('/').pop();
  const key = [property('font-family'), property('font-style'), property('font-weight')].join('|');
  if (byFile[file]) { aliases[key] = byFile[file]; continue; }
  byFile[file] = key;
  const font = fontkit.openSync(path.join(root, 'public/vendor/katex/fonts', file));
  // These TeX fonts have direct character maps, with no contextual shaping or
  // kerning tables. Fail explicitly if a future font needs a shaping engine.
  for (const table of ['GSUB', 'GPOS', 'kern', 'morx']) if (font.directory.tables[table]) throw new Error(file + ' requires shaping: ' + table);
  if (font.copyright) copyrights.add(font.copyright);
  const chars = {}, glyphs = {};
  for (const code of font.characterSet) {
    const glyph = font.glyphForCodePoint(code);
    chars[code] = glyph.id;
    if (!glyphs[glyph.id]) {
      const b = glyph.bbox;
      glyphs[glyph.id] = [glyph.advanceWidth, glyph.path.toSVG(), ...[b.minX, b.minY, b.maxX, b.maxY].map(bound)];
    }
  }
  const baseKey = key.replace(/^TDScript_([A-Za-z]+)\d\|/, 'KaTeX_$1|'), base = fonts[baseKey];
  if (base && baseKey !== key && JSON.stringify(base.chars) === JSON.stringify(chars) && base.em === font.unitsPerEm) {
    derived[key] = [baseKey, Object.fromEntries(Object.entries(glyphs).filter(([id, g]) => !same(base.glyphs[id], g)))];
  } else fonts[key] = { em: font.unitsPerEm, chars, glyphs };
}
const output = '/*! Glyph outlines from the bundled KaTeX fonts.\n' + [...copyrights].join('\n') + '\nSee public/vendor/katex/LICENSE (vendor/katex/LICENSE in the built app). */\n// Generated by scripts/generate-label-glyphs.js; do not edit the tables.\ntype Font = { em: number; chars: Record<number, number>; glyphs: Record<number, [number, string, number, number, number, number]> };\nconst fonts: Record<string, Font> = ' + JSON.stringify(fonts) + ';\n' +
  '// the script-size faces: their base face with these glyphs replaced\nconst derived: Record<string, [string, Font[\'glyphs\']]> = ' + JSON.stringify(derived) + ';\n' +
  'for (const [key, [base, glyphs]] of Object.entries(derived)) fonts[key] = { ...fonts[base], glyphs: { ...fonts[base].glyphs, ...glyphs } };\n' +
  '// faces that use another face\'s file\nconst aliases: Record<string, string> = ' + JSON.stringify(aliases) + ';\n' +
  'for (const [key, other] of Object.entries(aliases)) fonts[key] = fonts[other];\nexport default fonts;\n';
const target = path.join(root, 'src/domain/label-glyphs.ts');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Label glyph tables are stale');
} else fs.writeFileSync(target, output);
console.log(Object.keys(fonts).length + ' exact font outline tables; ' + Buffer.byteLength(output) + ' bytes');
